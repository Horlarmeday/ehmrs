      showBillDetailsModal: false,
      showPaymentModal: false,
      creating: false,

      // Selected bill for modals
      selectedBill: null,

      // Create bill form
      createBillForm: {
        patient_id: null,
        visit_id: null,
        billing_mode: 'CASH',
        payment_collection_method: 'POINT_OF_SERVICE',
        payment_collection_point: 'main-cashier',
        items: [],
        total_discount: 0,
        tax_amount: 0,
        final_amount: 0,
        due_date: '',
        notes: '',
      },

      // Options
      billingModeOptions: [
        { value: 'CASH', text: 'Cash' },
        { value: 'INSURANCE', text: 'Insurance' },
        { value: 'WAIVER', text: 'Waiver' },
        { value: 'OTHER', text: 'Other' },
        { value: 'FREE', text: 'Free' },
        { value: 'WALLET', text: 'Wallet' },
      ],
      paymentCollectionOptions: [
        { value: 'DEPOSIT', text: 'Deposit' },
        { value: 'POINT_OF_SERVICE', text: 'Point of Service' },
        { value: 'INSURANCE_CLAIM', text: 'Insurance Claim' },
        { value: 'MIXED', text: 'Mixed' },
      ],
      billingPointOptions: [
        { value: 'main-cashier', text: 'Main Cashier' },
        { value: 'accounting-office', text: 'Accounting Office' },
        { value: 'emergency-cashier', text: 'Emergency Cashier' },
      ],
      itemTypeOptions: [
        { value: 'DRUG', text: 'Drug' },
        { value: 'TEST', text: 'Test' },
        { value: 'INVESTIGATION', text: 'Investigation' },
        { value: 'SERVICE', text: 'Service' },
        { value: 'ADDITIONAL_ITEM', text: 'Additional Item' },
      ],

      // Data options
      patientOptions: [],
      visitOptions: [],
      itemOptions: {
        DRUG: [],
        TEST: [],
        INVESTIGATION: [],
        SERVICE: [],
        ADDITIONAL_ITEM: [],
      },
    };
  },
  computed: {
    billSubtotal() {
      return this.createBillForm.items.reduce((sum, item) => sum + (item.total_price || 0), 0);
    },
    bills() {
      return this.$store.getters['accounting/getClinicalBills'] || [];
    },
    totalRows() {
      return this.$store.getters['accounting/getClinicalBillsTotal'] || 0;
    },
    isLoading() {
      return this.$store.getters['accounting/loading'];
    },
    error() {
      return this.$store.getters['accounting/error'];
    },
    billsStats() {
      const bills = this.bills;
      return {
        totalBills: bills.length,
        totalRevenue: bills.reduce((sum, bill) => sum + (+bill.final_amount || 0), 0),
        pendingPayments: bills.filter((bill) => bill.payment_status === 'PENDING').length,
        autoGenerated: bills.filter((bill) => bill.is_auto_generated).length,
      };
    },
  },
  async mounted() {
    await this.loadBills();
    // await this.loadOptions();
  },
  methods: {
    async loadBills() {
      try {
        // Map frontend filters to backend expectations
        const params = {
          page: this.currentPage,
          limit: this.perPage,
          patient_id: this.filters.patient_id,
          billing_status: this.filters.billing_status || undefined,
          payment_status: this.filters.payment_status || undefined,
          start_date: this.filters.start_date || undefined,
          end_date: this.filters.end_date || undefined,
          min_amount: this.filters.min_amount || undefined,
          max_amount: this.filters.max_amount || undefined,
          billing_mode: this.filters.billing_mode || undefined,
        };

        // Remove undefined values
        Object.keys(params).forEach((key) => {
          if (params[key] === undefined || params[key] === null || params[key] === '') {
            delete params[key];
          }
        });

        await this.$store.dispatch('accounting/fetchClinicalBills', params);
      } catch (error) {
        console.error('Failed to load bills:', error);
      }
    },

    async refreshBills() {
      this.currentPage = 1;
      await this.loadBills();
    },

    onFiltersChanged(newFilters) {
      // Map frontend filter names to backend expectations
      const mappedFilters = {};

      if (newFilters.patientName) {
        // We need to search for patient ID based on name
        // For now, we'll skip patient filtering until we implement patient search
        console.log('Patient name filtering not yet implemented');
      }

      if (newFilters.billingStatus) {
        mappedFilters.billing_status = newFilters.billingStatus;
      }

      if (newFilters.paymentStatus) {
        mappedFilters.payment_status = newFilters.paymentStatus;
      }

      if (newFilters.dateFrom) {
        mappedFilters.start_date = newFilters.dateFrom;
      }

      if (newFilters.dateTo) {
        mappedFilters.end_date = newFilters.dateTo;
      }

      if (newFilters.amountRange) {
        const parts = newFilters.amountRange.split('-').map((s) => parseFloat(s.trim()));
        if (parts.length === 2 && !isNaN(parts[0]) && !isNaN(parts[1])) {
          mappedFilters.min_amount = parts[0];
          mappedFilters.max_amount = parts[1];
        }
      }

      if (newFilters.billingMode) {
        mappedFilters.billing_mode = newFilters.billingMode;
      }

      this.filters = { ...this.filters, ...mappedFilters };
      this.currentPage = 1;
      this.loadBills();
    },

    async loadOptions() {
      try {
        const patients = await this.$store.dispatch('patient/fetchPatients', {
          currentPage: 1,
          itemsPerPage: 50,
          search: '',
        });
        this.patientOptions = patients.map((patient) => ({
          value: patient.id,
          text: `${patient.firstname} ${patient.lastname} (${patient.hospital_id})`,
        }));

        // Load billing points using Vuex store
        const billingPoints = await this.$store.dispatch('accounting/fetchBillingPoints');
        this.billingPointOptions = billingPoints.map((point) => ({
          value: point.id,
          text: point.name,
        }));

        // Load items for each type using Vuex store
        await this.loadItemOptions();
      } catch (error) {
        console.error('Failed to load options:', error);
      }
    },

    async loadItemOptions() {
      try {
        // Load drugs using Vuex store
        const drugsResponse = await this.$store.dispatch('account/fetchPharmacyDrugs');
        this.itemOptions.DRUG = drugsResponse.map((drug) => ({
          value: drug.id,
          text: drug.name,
          price: drug.price,
        }));

        // Load tests using Vuex store
        const testsResponse = await this.$store.dispatch('account/fetchLaboratoryTests');
        this.itemOptions.TEST = testsResponse.map((test) => ({
          value: test.id,
          text: test.name,
          price: test.price,
        }));

        // Load services using Vuex store
        const servicesResponse = await this.$store.dispatch('account/fetchServices');
        this.itemOptions.SERVICE = servicesResponse.map((service) => ({
          value: service.id,
          text: service.name,
          price: service.price,
        }));

        // Similar for other item types...
      } catch (error) {
        console.error('Failed to load item options:', error);
      }
    },

    formatDate(dateString) {
      return new Date(dateString).toLocaleDateString('en-NG');
    },

    async onPatientChange() {
      this.billForm.visit_id = null;
      this.visitOptions = [];

      if (this.billForm.patient_id) {
        try {
          const visits = await this.$store.dispatch(
            'account/fetchPatientVisits',
            this.billForm.patient_id
          );
          this.visitOptions = visits.map((visit) => ({
            value: visit.id,
            text: `${this.formatDate(visit.date_visit_start)} - ${visit.type}`,
          }));
        } catch (error) {
          console.error('Failed to load visits:', error);
        }
      }
    },

    onVisitChange() {
      // Could load visit-specific data here
    },

    onItemTypeChange(index) {
      const item = this.billForm.items[index];
      item.item_id = null;
      item.unit_price = 0;
      item.total_price = 0;
    },

    onItemChange(index) {
      const item = this.billForm.items[index];
      const selectedItem = this.itemOptions[item.item_type].find((opt) => opt.id === item.item_id);

      if (selectedItem) {
        item.unit_price = selectedItem.price || 0;
        this.calculateItemTotal(index);
      }
    },

    calculateItemTotal(index) {
      const item = this.billForm.items[index];
      item.total_price = (item.quantity || 0) * (item.unit_price || 0);
      this.calculateBillTotal();
    },

    calculateBillTotal() {
      const subtotal = this.billSubtotal;
      const discount = this.billForm.total_discount || 0;
      const tax = this.billForm.tax_amount || 0;
      this.billForm.final_amount = subtotal - discount + tax;
    },

    addBillItem() {
      this.billForm.items.push({
        item_type: 'DRUG',
        item_id: null,
        quantity: 1,
        unit_price: 0,
        total_price: 0,
        notes: '',
      });
    },

    removeBillItem(index) {
      this.billForm.items.splice(index, 1);
      this.calculateBillTotal();
    },

    getItemOptions(itemType) {
      return this.itemOptions[itemType] || [];
    },

    // Modal actions
    openCreateBillModal() {
      this.showCreateBillModal = true;
    },

    viewBill(bill) {
      this.selectedBill = bill;
      this.showBillDetailsModal = true;
    },

    editBill(bill) {
      this.selectedBill = bill;
      this.showBillDetailsModal = true;
    },

    processPayment(bill) {
      this.selectedBill = bill;
      this.showPaymentModal = true;
    },

