    manageItems(bill) {
      // Navigate to bill items management page
      this.$router.push({
        name: 'bill-items',
        params: { billId: bill.id },
      });
    },

    async loadBillForEdit(billId) {
      try {
        const bill = await this.$store.dispatch('accounting/getClinicalBillById', billId);

        if (bill) {
          this.billForm = {
            patient_id: bill.patient_id,
            visit_id: bill.visit_id,
            billing_mode: bill.billing_mode,
            payment_collection_method: bill.payment_collection_method,
            payment_collection_point: bill.payment_collection_point,
            items:
              bill.billItems?.map((item) => ({
                item_type: item.item_type,
                item_id: item.item_id,
                quantity: item.quantity,
                unit_price: item.unit_price,
                total_price: item.total_price,
                notes: item.notes,
              })) || [],
            total_discount: bill.total_discount || 0,
            tax_amount: bill.tax_amount || 0,
            final_amount: bill.final_amount,
            due_date: bill.due_date,
            notes: bill.notes,
          };
        }
      } catch (error) {
        console.error('Failed to load bill for edit:', error);
      }
    },

    async saveBill() {
      try {
        this.saving = true;

        let result;
        if (this.isEditing) {
          result = await this.$store.dispatch('account/updateBill', {
            id: this.billForm.id,
            billData: this.billForm,
          });
          if (result.success) {
            this.$bvToast.toast('Bill updated successfully', {
              title: 'Success',
              variant: 'success',
              solid: true,
            });
          }
        } else {
          result = await this.$store.dispatch('account/createBill', this.billForm);
          if (result.success) {
            this.$bvToast.toast('Bill created successfully', {
              title: 'Success',
              variant: 'success',
              solid: true,
            });
          }
        }

        if (result.success) {
          this.showBillModal = false;
          this.resetBillForm();
        } else {
          this.$bvToast.toast(result.error || 'Failed to save bill', {
            title: 'Error',
            variant: 'danger',
            solid: true,
          });
        }
      } catch (error) {
        console.error('Failed to save bill:', error);
        this.$bvToast.toast('Failed to save bill', {
          title: 'Error',
          variant: 'danger',
          solid: true,
        });
      } finally {
        this.saving = false;
      }
    },

    resetBillForm() {
      this.billForm = {
        patient_id: null,
        visit_id: null,
        billing_mode: 'CASH',
        payment_collection_method: 'POINT_OF_SERVICE',
        payment_collection_point: 'main-cashier',
        items: [],
        total_discount: 0,
        tax_amount: 0,
        final_amount: 0,
        due_date: '',
        notes: '',
      };
      this.isEditing = false;
    },

    // Event handlers for modals
    onBillUpdated() {
      // Refresh bills after update
      this.loadBills();
      this.$bvToast.toast('Bill updated successfully', {
        title: 'Success',
        variant: 'success',
        solid: true,
      });
    },

    onPaymentProcessed() {
      // Refresh bills after payment
      this.loadBills();
      this.$bvToast.toast('Payment processed successfully', {
        title: 'Success',
        variant: 'success',
        solid: true,
      });
    },

    // Utility methods
    formatCurrency(amount) {
      return new Intl.NumberFormat('en-NG', {
        style: 'currency',
        currency: 'NGN',
      }).format(amount || 0);
    },

    getBillingStatusVariant(status) {
      const variants = {
        DRAFT: 'secondary',
        PENDING: 'warning',
        APPROVED: 'success',
        REJECTED: 'danger',
      };
      return variants[status] || 'secondary';
    },

    getPaymentStatusVariant(status) {
      const variants = {
        PENDING: 'warning',
        PARTIAL: 'info',
        PAID: 'success',
        CANCELLED: 'danger',
      };
      return variants[status] || 'secondary';
    },

    // Filter methods
    clearFilters() {
      this.filters = {
        patientName: '',
        billingStatus: '',
        paymentStatus: '',
        dateRange: '',
      };
      this.loadBills();
    },

    debounceSearch: debounce(function () {
      this.loadBills();
    }, 500),

    onPageChange(page) {
      this.currentPage = page;
      this.loadBills();
    },

    exportBills() {
      // Implement export functionality
      this.$bvToast.toast('Export functionality coming soon', {
        title: 'Info',
        variant: 'info',
        solid: true,
      });
    },
  },
};

// Debounce utility function
function debounce(func, wait) {
  let timeout;
  return function executedFunction(...args) {
    const later = () => {
      clearTimeout(timeout);
      func(...args);
    };
    clearTimeout(timeout);
    timeout = setTimeout(later, wait);
  };
}
