  name: 'BillManagement',
  components: {
    BillTable,
    BillFilters,
    BillDetailsModal,
    PaymentProcessingModal,
  },
  data() {
    return {
      // Filters - Must match backend BillSearchFilters interface
      filters: {
        patient_id: null,
        billing_status: '',
        payment_status: '',
        start_date: '',
        end_date: '',
        min_amount: null,
        max_amount: null,
        billing_mode: '',
        page: 1,
        limit: 10,
